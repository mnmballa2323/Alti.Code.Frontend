import fs from 'fs/promises';
import path from 'path';
import { exec } from 'child_process';
import { promisify } from 'util';
import { logger } from '../../../shared/logger.js';

const execPromise = promisify(exec);

/**
 * Ensures a directory exists.
 */
async function ensureDir(dirPath) {
  await fs.mkdir(dirPath, { recursive: true });
}

/**
 * Phase 1: Analyze Codebase
 */
async function runAnalyze(workspacePath, appName) {
  logger.info(`🔍 [CLI-Anything] [Phase 1: Analyze] Scanning workspace: ${workspacePath}`);
  
  // Real directory scan
  let files = [];
  try {
    files = await fs.readdir(workspacePath);
  } catch (err) {
    // If workspace doesn't exist, create it
    await ensureDir(workspacePath);
    files = [];
  }

  const structure = {
    hasPackageJson: files.includes('package.json'),
    hasPyProject: files.includes('pyproject.toml') || files.includes('setup.py'),
    hasReadme: files.includes('README.md'),
    totalFiles: files.length,
    filesList: files.slice(0, 10),
  };

  const analysisReport = `
# Codebase Analysis Report for ${appName}
* Generated by Inso Code CLI-Anything *
* Timestamp: ${new Date().toISOString()} *

## Workspace Attributes:
- **Workspace Path:** ${workspacePath}
- **Detected Language/Config:** ${structure.hasPackageJson ? 'JavaScript/Node' : structure.hasPyProject ? 'Python' : 'Generic/Mixed'}
- **README Present:** ${structure.hasReadme ? 'Yes' : 'No'}
- **Total Root Files:** ${structure.totalFiles}

## Scanned Files:
${files.map(f => `- ${f}`).join('\n') || '- (Empty directory)'}
  `.trim();

  await fs.writeFile(path.join(workspacePath, 'analysis_report.md'), analysisReport);
  return { status: 'SUCCESS', details: structure };
}

/**
 * Phase 2: Design CLI Schema
 */
async function runDesign(workspacePath, appName) {
  logger.info(`📐 [CLI-Anything] [Phase 2: Design] Designing CLI commands for ${appName}`);

  const cliSchema = {
    appName: appName.toLowerCase().replace(/[^a-z0-9]/g, '_'),
    commands: [
      { name: 'status', description: 'Show stateful status of the target application.', args: [] },
      { name: 'execute', description: 'Trigger core execution action.', args: ['--action', '--payload'] },
      { name: 'history', description: 'View history of stateful actions in this session.', args: [] },
      { name: 'undo', description: 'Rollback last state change.', args: [] },
      { name: 'redo', description: 'Re-apply last rolled-back state change.', args: [] }
    ],
    stateModel: {
      sessionFile: `.cli_${appName.toLowerCase()}_session.json`,
      initialState: { history: [], pointer: -1, app: appName, status: 'idle' }
    }
  };

  await fs.writeFile(
    path.join(workspacePath, 'cli_schema.json'),
    JSON.stringify(cliSchema, null, 2)
  );

  return { status: 'SUCCESS', schema: cliSchema };
}

/**
 * Phase 3: Implement Stateful CLI Harness (Python Click + REPL + Undo/Redo)
 */
async function runImplement(workspacePath, appName, schema) {
  logger.info(`🛠️ [CLI-Anything] [Phase 3: Implement] Generating source code for ${appName} CLI`);

  const harnessCode = `
# -*- coding: utf-8 -*-
"""
Generated by Inso Code CLI-Anything
Harness for stateful interaction with: ${appName}
"""

import os
import sys
import json
import click

SESSION_FILE = "${schema.stateModel.sessionFile}"

def load_session():
    if not os.path.exists(SESSION_FILE):
        return ${JSON.stringify(schema.stateModel.initialState)}
    try:
        with open(SESSION_FILE, 'r') as f:
            return json.load(f)
    except:
        return ${JSON.stringify(schema.stateModel.initialState)}

def save_session(session):
    with open(SESSION_FILE, 'w') as f:
        json.dump(session, f, indent=2)

@click.group(invoke_without_command=True)
@click.option('--json-out', is_flag=True, help='Output results in structured machine-readable JSON.')
@click.pass_context
def cli(ctx, json_out):
    """${appName} Agent-Native Stateful Command Line Interface."""
    ctx.ensure_object(dict)
    ctx.obj['JSON_OUT'] = json_out
    
    if ctx.invoked_subcommand is None:
        # Launch Interactive REPL Mode for Agents
        click.echo("🌌 Welcome to ${appName} REPL Mode. Type 'exit' or '--help' to control.")
        while True:
            try:
                cmd_line = input("${schema.appName}› ").strip()
                if not cmd_line:
                    continue
                if cmd_line.lower() in ['exit', 'quit']:
                    break
                # Simple parser wrapper for inner REPL commands
                os.system(f"python cli_harness.py {cmd_line}")
            except (KeyboardInterrupt, EOFError):
                break

@cli.command()
@click.pass_context
def status(ctx):
    """Show the stateful application status."""
    session = load_session()
    result = {
        "app": session["app"],
        "status": session["status"],
        "history_depth": len(session["history"]),
        "history_pointer": session["pointer"]
    }
    if ctx.obj.get('JSON_OUT'):
        click.echo(json.dumps(result))
    else:
        click.echo(f"📊 Status: {result['status'].upper()}")
        click.echo(f"📈 History Depth: {result['history_depth']} actions (ptr: {result['history_pointer']})")

@cli.command()
@click.option('--action', required=True, help='Action to perform.')
@click.option('--payload', default='{}', help='JSON payload.')
@click.pass_context
def execute(ctx, action, payload):
    """Execute a state-changing action."""
    session = load_session()
    
    # Prune forward history if pointer was rolled back
    if session["pointer"] < len(session["history"]) - 1:
        session["history"] = session["history"][:session["pointer"] + 1]
        
    action_entry = {
        "id": len(session["history"]) + 1,
        "action": action,
        "payload": payload,
        "timestamp": "${new Date().toISOString()}"
    }
    
    session["history"].append(action_entry)
    session["pointer"] = len(session["history"]) - 1
    session["status"] = f"active_action_{action}"
    
    save_session(session)
    
    result = {
        "success": True,
        "executed_action": action_entry,
        "status": session["status"]
    }
    
    if ctx.obj.get('JSON_OUT'):
        click.echo(json.dumps(result))
    else:
        click.echo(f"🚀 Action '{action}' executed successfully.")

@cli.command()
@click.pass_context
def undo(ctx):
    """Undo the last state change."""
    session = load_session()
    if session["pointer"] < 0:
        err = {"success": False, "error": "No actions to undo."}
        if ctx.obj.get('JSON_OUT'):
            click.echo(json.dumps(err))
        else:
            click.echo("⚠️ Nothing to undo.")
        return
        
    action = session["history"][session["pointer"]]
    session["pointer"] -= 1
    session["status"] = f"undid_action_{action['action']}"
    
    save_session(session)
    
    result = {
        "success": True,
        "undone_action": action,
        "new_pointer": session["pointer"]
    }
    
    if ctx.obj.get('JSON_OUT'):
        click.echo(json.dumps(result))
    else:
        click.echo(f"⏪ Undone: '{action['action']}' action reverted.")

@cli.command()
@click.pass_context
def redo(ctx):
    """Redo the last rolled-back state change."""
    session = load_session()
    if session["pointer"] >= len(session["history"]) - 1:
        err = {"success": False, "error": "No actions to redo."}
        if ctx.obj.get('JSON_OUT'):
            click.echo(json.dumps(err))
        else:
            click.echo("⚠️ Nothing to redo.")
        return
        
    session["pointer"] += 1
    action = session["history"][session["pointer"]]
    session["status"] = f"redid_action_{action['action']}"
    
    save_session(session)
    
    result = {
        "success": True,
        "redone_action": action,
        "new_pointer": session["pointer"]
    }
    
    if ctx.obj.get('JSON_OUT'):
        click.echo(json.dumps(result))
    else:
        click.echo(f"⏩ Redone: '{action['action']}' action re-applied.")

@cli.command()
@click.pass_context
def history(ctx):
    """View session history log."""
    session = load_session()
    if ctx.obj.get('JSON_OUT'):
        click.echo(json.dumps(session["history"]))
    else:
        click.echo("📜 History Trail:")
        for idx, entry in enumerate(session["history"]):
            marker = "➡️" if idx === session["pointer"] else " "
            click.echo(f"{marker} [{entry['id']}] {entry['action']} ({entry['payload']})")

if __name__ === '__main__':
    cli(obj={})
  `.trim();

  await fs.writeFile(path.join(workspacePath, 'cli_harness.py'), harnessCode);
  return { status: 'SUCCESS', file: 'cli_harness.py' };
}

