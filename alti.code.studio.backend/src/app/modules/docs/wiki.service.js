import { GeminiAiService } from '../gemini/gemini.service.js';
import { logger } from '../../../shared/logger.js';
import fs from 'fs/promises';
import path from 'path';

/** All file outputs are resolved relative to cwd() — never relative strings. */
const CWD = process.cwd();
const DOCS_DIR = path.join(CWD, 'docs');
const ADR_DIR = path.join(DOCS_DIR, 'adr');
const ARCH_PATH = path.join(CWD, 'ARCHITECTURE.md');
const DOCS_ARCH = path.join(DOCS_DIR, 'ARCHITECTURE.md');

class WikiService {
    /**
     * Scan the modules directory, ask the LLM for an ARCHITECTURE.md, and
     * write it to the project root.
     * @returns {Promise<string>} The generated markdown content
     */
    async generateArchitecture() {
        logger.info('🏰 The Librarian: Scanning project structure...');

        try {
            const modulesDir = path.join(CWD, 'src', 'app', 'modules');
            const modules = await fs.readdir(modulesDir);

            const structure = `
                Project: Inso Code Backend
                Modules Found: ${modules.join(', ')}
            `;

            const prompt = `
                You are a System Architect.
                Generate a high-level ARCHITECTURE.md file for this project based on the modules list.
                
                Project Structure:
                ${structure}

                Format:
                # System Architecture
                ## Overview
                [Abstract]
                ## Modules
                [List each module with a predicted purpose based on its name]
                
                Keep it professional and concise.
            `;

            logger.info('🏰 The Librarian: Writing History (Wiki)...');
            const markdown = await GeminiAiService.generateContent(prompt);

            await fs.writeFile(ARCH_PATH, markdown);
            logger.info(`✅ ARCHITECTURE.md generated → ${ARCH_PATH}`);
            return markdown;

        } catch (error) {
            logger.error(`❌ Wiki Gen Failed: ${error.message}`);
            throw error;
        }
    }

    /**
     * Generate a full static documentation site under /docs.
     * @returns {Promise<{ status: string, path: string }>}
     */
    async generateDocsSite() {
        logger.info('🏰 The Librarian: Building Documentation Site...');

        try {
            await fs.mkdir(DOCS_DIR, { recursive: true });
            await fs.mkdir(ADR_DIR, { recursive: true });

            // 1. Landing Page
            const indexContent = `# Inso Code Documentation

Welcome to the living documentation of Inso Code.

## Sections
- [Architecture](ARCHITECTURE.md)
- [ADRs (Architectural Decisions)](adr/)
- [API Reference](api/)

*Generated by The Archivist*`.trim();

            await fs.writeFile(path.join(DOCS_DIR, 'index.md'), indexContent);

            // 2. Architecture Page — generate if missing
            const archExists = await fs.stat(ARCH_PATH).then(() => true).catch(() => false);
            if (!archExists) {
                logger.info('🏰 ARCHITECTURE.md not found — generating...');
                await this.generateArchitecture();
            }
            await fs.copyFile(ARCH_PATH, DOCS_ARCH);

            // 3. Sidebar (for Docsify/VitePress etc.)
            const sidebar = `* [Home](/)\n* [Architecture](ARCHITECTURE.md)\n* [Decisions](adr/)`.trim();
            await fs.writeFile(path.join(DOCS_DIR, '_sidebar.md'), sidebar);

            logger.info(`✅ Docs site structure generated → ${DOCS_DIR}`);
            return { status: 'success', path: DOCS_DIR };

        } catch (error) {
            logger.error('❌ Wiki Docs Site Gen Failed', error);
            throw error;
        }
    }

    /**
     * Generate and save an Architecture Decision Record (ADR).
     * @param {string} title    - Short, imperative title (e.g. "Use PostgreSQL for persistence")
     * @param {string} context  - Background context for the decision
     * @returns {Promise<{ path: string, content: string }>}
     */
    async generateADR(title, context) {
        if (!title || typeof title !== 'string' || title.trim().length === 0) {
            throw new Error('WikiService: title must be a non-empty string.');
        }
        if (!context || typeof context !== 'string' || context.trim().length === 0) {
            throw new Error('WikiService: context must be a non-empty string.');
        }

        logger.info(`📄 The Librarian: Generating ADR — "${title}"`);

        await fs.mkdir(ADR_DIR, { recursive: true });

        const prompt = `
            You are a Staff Software Architect writing an Architecture Decision Record (ADR).

            Title: "${title}"
            Context: "${context}"

            Write a concise ADR in this format:
            # ADR: ${title}
            ## Status
            Accepted
            ## Context
            [Describe the situation]
            ## Decision
            [What was decided]
            ## Consequences
            [Positive and negative consequences]

            Return only the markdown content.
        `;

        const content = await GeminiAiService.generateContent(prompt);
        const slug = title.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
        const timestamp = new Date().toISOString().replace(/[:.]/g, '-').slice(0, 19);
        const filename = `${timestamp}-${slug}.md`;
        const filePath = path.join(ADR_DIR, filename);

        await fs.writeFile(
            filePath,
            content
                .replace(/^```markdown\n?/m, '')
                .replace(/^```\n?/m, '')
                .replace(/\n?```$/m, '')
                .trim()
        );
        logger.info(`✅ ADR saved → ${filePath}`);

        // Phase 5: Automatically inject ADRs into AI memory for future RAG
        import('../memory/vector.store.js').then(({ vectorStoreService }) => {
            vectorStoreService.add(`ADR: ${title}\nContext: ${context}\nContent: ${content}`, {
                type: 'wiki_adr',
                slug,
                title
            }).catch(e => logger.warn(`Failed to embed ADR into Vector Store: ${e.message}`));
        }).catch(() => logger.warn('Vector store not available for ADR embedding'));

        return { path: filePath, filename, content };
    }

    /**
     * List all ADRs in the adr/ directory with metadata.
     * @returns {Promise<Array<{ filename: string, createdAt: Date, sizeBytes: number }>>}
     */
    async listADRs() {
        try {
            await fs.mkdir(ADR_DIR, { recursive: true });
            const entries = await fs.readdir(ADR_DIR, { withFileTypes: true });
            const files = await Promise.all(
                entries
                    .filter(e => e.isFile() && e.name.endsWith('.md'))
                    .map(async e => {
                        const stat = await fs.stat(path.join(ADR_DIR, e.name));
                        return { filename: e.name, createdAt: stat.birthtime, sizeBytes: stat.size };
                    })
            );
            return files.sort((a, b) => b.createdAt - a.createdAt);
        } catch {
            return [];
        }
    }
    /**
     * Create a knowledge article from a completed sprint.
     * Called automatically by the sprintBus sprint:completed hook.
     * Saves to docs/sprint-articles/sprint-<id>.md
     *
     * @param {object} sprintData  - { sprintId, goal, status, steps, testResults, review, totalCostUsd, durationMs }
     * @returns {Promise<{ path: string, title: string, slug: string, createdAt: string }>}
     */
    async createSprintArticle(sprintData) {
        const { sprintId, goal, status, steps = [], testResults, review, totalCostUsd, durationMs } = sprintData;
        const articlesDir = path.join(CWD, 'docs', 'sprint-articles');
        await fs.mkdir(articlesDir, { recursive: true });

        const stepSummary = steps
            .map((s, i) => `${i + 1}. [${s.status}] ${s.description}`)
            .join('\n');

        const prompt = `You are The Archivist — an autonomous technical writer. A software sprint just completed. Write a concise knowledge article about it.

Sprint ID: ${sprintId}
Goal: "${goal}"
Status: ${status}
Duration: ${Math.round((durationMs || 0) / 1000)}s | Cost: $${(totalCostUsd || 0).toFixed(4)}
Steps completed:\n${stepSummary.substring(0, 1000)}
Tests: ${testResults ? (testResults.passed ? 'PASSED' : 'FAILED') + ` (${testResults.results?.length ?? 0} files)` : 'skipped'}
Self-heals: ${testResults?.healLog?.length ?? 0}
Review score: ${review?.score ?? 'n/a'}/100

Write a concise knowledge article (3-5 paragraphs) covering:
1. What was changed and why
2. How tests fared and any self-healing that occurred
3. Key lessons for future sprints

Return only markdown content.`.trim();

        let content = '';
        try {
            content = await GeminiAiService.generateContent(prompt);
            content = content.replace(/^```[a-z]*\n?/m, '').replace(/\n?```$/m, '').trim();
        } catch (e) {
            content = `# Sprint ${sprintId}\n\n**Goal**: ${goal}\n\n**Status**: ${status}\n\nSprint completed in ${Math.round((durationMs || 0) / 1000)}s.`;
        }

        const title = `Sprint ${sprintId}: ${goal.substring(0, 60)}`;
        const slug = `sprint-${sprintId}`;
        const timestamp = new Date().toISOString();
        const filePath = path.join(articlesDir, `${slug}.md`);
        const fullContent = `---\ntitle: "${title}"\nsprintId: ${sprintId}\nstatus: ${status}\ncreatedAt: ${timestamp}\n---\n\n${content}`;

        await fs.writeFile(filePath, fullContent);
        logger.info(`📚 Wiki: Article written → ${filePath}`);
        return { path: filePath, title, slug, createdAt: timestamp };
    }

    /**
     * List all sprint knowledge articles.
     * @returns {Promise<Array<{ title, slug, createdAt, sizeBytes }>>}
     */
    async listArticles() {
        const articlesDir = path.join(CWD, 'docs', 'sprint-articles');
        try {
            await fs.mkdir(articlesDir, { recursive: true });
            const entries = await fs.readdir(articlesDir, { withFileTypes: true });
            const files = await Promise.all(
                entries
                    .filter(e => e.isFile() && e.name.endsWith('.md'))
                    .map(async e => {
                        const stat = await fs.stat(path.join(articlesDir, e.name));
                        // Parse frontmatter title
                        let title = e.name;
                        let createdAt = stat.birthtime.toISOString();
                        try {
                            const raw = await fs.readFile(path.join(articlesDir, e.name), 'utf-8');
                            const titleMatch = raw.match(/^title: "(.+)"/m);
                            const dateMatch = raw.match(/^createdAt: (.+)/m);
                            if (titleMatch) title = titleMatch[1];
                            if (dateMatch) createdAt = dateMatch[1].trim();
                        } catch { }
                        return { title, slug: e.name.replace('.md', ''), createdAt, sizeBytes: stat.size };
                    })
            );
            return files.sort((a, b) => new Date(b.createdAt) - new Date(a.createdAt));
        } catch {
            return [];
        }
    }
}

export const wikiService = new WikiService();

// ── v6.6.0: Auto-generate knowledge article on sprint completion ────────────
import { sprintBus } from '../autonomousSprint/autonomousSprint.service.js';
import { vectorStoreService } from '../memory/vector.store.js';

sprintBus.on('sprint:completed', async (data) => {
    try {
        const article = await wikiService.createSprintArticle(data);
        logger.info(`📚 Wiki: Auto-article created for sprint ${data.sprintId} → ${article.slug}`);
        // Index article into vector store for future GoalSynthesizer dedup
        await vectorStoreService.add(
            `Sprint article: ${article.title} | status=${data.status} | goal=${data.goal}`,
            { type: 'wiki_article', sprintId: data.sprintId, slug: article.slug }
        ).catch(() => { });
    } catch (e) {
        logger.warn(`📚 Wiki: Auto-article failed for sprint ${data.sprintId} — ${e.message}`);
    }
});

